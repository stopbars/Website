test('extracts only the requested airport and maps X-Plane light codes', () => {
  const result = parseAptDatAirport(APT_FIXTURE, {
    icao: 'YSCB',
    sourceFile: 'Global Airports/Earth nav data/apt.dat',
  });

  assert.equal(result.airportIdentifier, 'YSCB');
  assert.equal(result.airportName, 'Canberra');
  assert.equal(result.runways.length, 1);
  assert.equal(result.runways[0].sourceType, 'xplane-runway');
  assert.equal(result.runways[0].materialKind, 'asphalt-medium');
  assert.equal(result.runways[0].first.markingCode, 3);
  assert.ok(result.runways[0].lengthMeters > 1000);
  assert.ok(result.runwayLightZones.length > 0);
  assert.deepEqual(
    result.runwayLightZones
      .filter(
        (zone) =>
          zone.lightType.includes('runway-edge-') && zone.lightType.endsWith('-continuous-envelope')
      )
      .map((zone) => zone.geometryType),
    ['LineString', 'LineString']
  );
  assert.deepEqual(
    result.lightRows
      .filter((row) => row.sourceType === 'xplane-apt-light-string')
      .map((row) => [row.lightCode, row.classification]),
    [
      [101, 'taxi-centerline'],
      [103, 'stopbar'],
      [102, 'taxi-edge'],
    ]
  );
  assert.ok(result.lightRows[0].vertices.length > 3, 'Bezier light strings are sampled');
  assert.equal(result.lightRows[0].sourceType, 'xplane-apt-light-string');
  assert.match(result.lightRows[0].sourceFeatureId, /^[a-f0-9]{16}$/);
  assert.equal(result.lightRows[0].sourceRunIndex, 0);
  const markings = result.lightRows.filter(
    (row) => row.sourceType === 'xplane-apt-painted-marking'
  );
  assert.deepEqual(
    markings.map((row) => [row.markingCode, row.classification]),
    [
      [1, 'taxi-centerline'],
      [4, 'stopbar'],
    ]
  );
  assert.ok(markings.every((row) => row.placementOnly && row.removalEligible === false));

  const scene = buildReferenceScene(result, 'xplane');
  assert.ok(
    scene.features.some(
      (feature) =>
        feature.properties.sourceType === 'xplane-apt-runway-generated' &&
        feature.properties.semanticType === 'runway-marking'
    )
  );
  const runwayCentreline = scene.features.find(
    (feature) =>
      feature.properties.sourceType === 'xplane-apt-runway-generated' &&
      feature.geometry.type === 'LineString' &&
      feature.properties.semanticType === 'runway-marking'
  );
  assert.equal(runwayCentreline.properties.markingColor, '#f5f5f4');
  assert.equal(runwayCentreline.properties.renderPattern, 'apt-marking-22');
  assert.ok(
    scene.features.some(
      (feature) =>
        feature.geometry.type === 'Polygon' && feature.properties.title === 'Runway designation 17'
    )
  );
  assert.ok(scene.features.some((feature) => feature.properties.lightColor));
});

