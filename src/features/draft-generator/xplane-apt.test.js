test('extracts helipads, taxi routes, signs, and ramp starts as optional map signals', () => {
  const result = parseAptDatAirport(
    `I
1200 Test
1 10 0 0 TEST Detailed airport
102 H1 -31.0000 115.0000 90 20 18 53 0 0 0.25 1
20 -31.0001 115.0001 180 0 2 {@L}A
1200
1201 -31.0000 115.0000 both 10 A_start
1201 -31.0002 115.0002 both 11 A_end
1202 10 11 twoway taxiway_c A
1300 -31.0003 115.0003 90 gate jets A1
`,
    { icao: 'TEST' }
  );
  const types = result.referenceFeatures.map((feature) => feature.properties.semanticType);

  assert.ok(types.includes('helipad'));
  assert.ok(types.includes('taxiway-sign'));
  assert.ok(types.includes('atc-taxi-route'));
  assert.ok(types.includes('ramp-start'));
  assert.equal(
    result.referenceFeatures.find((feature) => feature.properties.semanticType === 'helipad')
      .properties.materialKind,
    'concrete-medium'
  );
});

test('collapses WED split Bezier records instead of drawing zero-length connector loops', () => {
  const result = parseAptDatAirport(
    `I
1200 Test
1 10 0 0 TEST Split bezier
120 Curved centreline
111 -31.0000 115.0000 1 101
112 -31.0001 115.0001 -31.00005 115.00005 1 101
111 -31.0001 115.0001 1 101
112 -31.0001 115.0001 -31.00015 115.00015 1 101
115 -31.0002 115.0002
`,
    { icao: 'TEST' }
  );

  const vertices = result.lightRows.find(
    (row) => row.sourceType === 'xplane-apt-light-string'
  ).vertices;
  assert.ok(vertices.length > 4);
  assert.equal(
    vertices.filter(
      (vertex, index) =>
        index > 0 &&
        vertex.lat === vertices[index - 1].lat &&
        vertex.lon === vertices[index - 1].lon
    ).length,
    0
  );
  assert.ok(vertices.every((vertex) => vertex.lat <= -31 && vertex.lat >= -31.0002));
  assert.ok(vertices.every((vertex) => vertex.lon >= 115 && vertex.lon <= 115.0002));
});

