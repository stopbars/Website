test('keeps apt.dat pavement holes in the same polygon and rejects open contours', () => {
  const result = parseAptDatAirport(
    `I
1200 Test
1 10 0 0 TEST Pavement rings
110 1 0.25 0 Apron with island
111 -31.0000 115.0000
111 -31.0000 115.0010
111 -31.0010 115.0010
113 -31.0010 115.0000
111 -31.0003 115.0003
111 -31.0007 115.0003
111 -31.0007 115.0007
113 -31.0003 115.0007
110 2 0.25 0 Broken pavement
111 -31.0020 115.0000
111 -31.0020 115.0010
115 -31.0030 115.0010
`,
    { icao: 'TEST', sourceFile: 'Earth nav data/apt.dat' }
  );

  assert.equal(result.referenceFeatures.length, 1);
  assert.equal(result.referenceFeatures[0].geometry.type, 'Polygon');
  assert.equal(result.referenceFeatures[0].geometry.coordinates.length, 2);
  assert.ok(result.referenceFeatures[0].geometry.coordinates.every((ring) => ring.length === 5));
  assert.match(result.warnings[0], /ignored open apt\.dat pavement contour/);
});
